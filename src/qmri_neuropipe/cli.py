def _counts_table(title: str, counts: dict[str, int]) -> Table:
    table = Table(title=title)
    table.add_column("Type", style="bold")
    table.add_column("Count", justify="right", style="cyan")
    for name, count in counts.items():
        table.add_row(name, str(count))
    return table


def _print_inventory(inventory, *, details: bool = False) -> None:
    overview = Table(title=inventory.name or "BIDS Dataset")
    overview.add_column("Property", style="bold")
    overview.add_column("Value", style="cyan")
    overview.add_row("Path", inventory.path)
    if inventory.rawdata_path != inventory.path:
        overview.add_row("Raw data", inventory.rawdata_path)
    overview.add_row("BIDS version", inventory.bids_version or "Unknown")
    overview.add_row("Participants", str(inventory.n_subjects))
    overview.add_row("Distinct session labels", str(inventory.n_sessions))
    overview.add_row("Participant/session observations", str(inventory.n_observations))
    overview.add_row("Sessionless participants", str(len(inventory.sessionless_subjects)))
    overview.add_row("Primary data files", str(inventory.raw_data.n_files))
    console.print(overview)

    if inventory.raw_data.modality_coverage:
        coverage = Table(title="Modality coverage")
        coverage.add_column("Modality", style="bold")
        coverage.add_column("Subjects", justify="right")
        coverage.add_column("Observations", justify="right")
        coverage.add_column("Files", justify="right", style="cyan")
        coverage.add_column("Data types")
        for modality, counts in inventory.raw_data.modality_coverage.items():
            coverage.add_row(
                modality,
                str(counts.n_subjects),
                str(counts.n_observations),
                str(counts.n_files),
                ", ".join(counts.suffixes),
            )
        console.print(coverage)
    if inventory.raw_data.suffixes:
        console.print(_counts_table("Raw data by suffix", inventory.raw_data.suffixes))

    if inventory.derivatives:
        table = Table(title="Derivative datasets")
        table.add_column("Dataset", style="bold")
        table.add_column("Generated by")
        table.add_column("Participants", justify="right")
        table.add_column("Observations", justify="right")
        for derivative in inventory.derivatives:
            producers = ", ".join(
                " ".join(str(item) for item in (producer.get("Name"), producer.get("Version")) if item)
                for producer in derivative.generated_by
            ) or "Unknown"
            table.add_row(
                derivative.name,
                producers,
                str(derivative.n_subjects),
                str(derivative.n_observations),
            )
        console.print(table)

        coverage = Table(title="Derivative model coverage")
        coverage.add_column("Derivative", style="bold")
        coverage.add_column("Modality")
        coverage.add_column("Subjects", justify="right")
        coverage.add_column("Observations", justify="right")
        coverage.add_column("Models", style="cyan")
        for derivative in inventory.derivatives:
            for modality, counts in derivative.products.items():
                coverage.add_row(
                    derivative.name,
                    modality,
                    str(counts.n_subjects),
                    str(counts.n_observations),
                    ", ".join(counts.models) or "—",
                )
        if coverage.row_count:
            console.print(coverage)

        downstream = Table(title="Downstream derivative coverage")
        downstream.add_column("Derivative", style="bold")
        downstream.add_column("Modality")
        downstream.add_column("ROI stats", justify="right")
        downstream.add_column("Normalized", justify="right")
        downstream.add_column("Template spaces", style="cyan")
        for derivative in inventory.derivatives:
            for modality, counts in derivative.products.items():
                denominator = counts.n_observations
                downstream.add_row(
                    derivative.name,
                    modality,
                    f"{counts.roi_stats_observations}/{denominator}" if denominator else "—",
                    f"{counts.normalized_observations}/{denominator}" if denominator else "—",
                    ", ".join(counts.template_spaces) or "—",
                )
        if downstream.row_count:
            console.print(downstream)

        if details:
            model_details = Table(title="Detailed model coverage")
            model_details.add_column("Derivative", style="bold")
            model_details.add_column("Modality")
            model_details.add_column("Model", style="cyan")
            model_details.add_column("Subjects", justify="right")
            model_details.add_column("Observations", justify="right")
            for derivative in inventory.derivatives:
                for modality, products in derivative.products.items():
                    for model, counts in products.model_coverage.items():
                        model_details.add_row(
                            derivative.name,
                            modality,
                            model,
                            str(counts.n_subjects),
                            str(counts.n_observations),
                        )
            if model_details.row_count:
                console.print(model_details)

    if inventory.processing_gaps:
        gaps = Table(title="Processing gaps")
        gaps.add_column("Modality", style="bold")
        gaps.add_column("Raw observations", justify="right")
        gaps.add_column("Processed", justify="right")
        gaps.add_column("Missing", justify="right", style="yellow")
        gaps.add_column("Coverage", justify="right", style="cyan")
        for modality, counts in inventory.processing_gaps.items():
            coverage_pct = (
                100.0 * counts.processed_observations / counts.raw_observations
                if counts.raw_observations
                else 0.0
            )
            gaps.add_row(
                modality,
                str(counts.raw_observations),
                str(counts.processed_observations),
                str(counts.missing_observations),
                f"{coverage_pct:.1f}%",
            )
        console.print(gaps)

        if details:
            missing = Table(title="Missing derivative observations")
            missing.add_column("Modality", style="bold")
            missing.add_column("Subject/session observations", style="yellow")
            for modality, counts in inventory.processing_gaps.items():
                if counts.missing:
                    missing.add_row(modality, ", ".join(counts.missing))
            if missing.row_count:
                console.print(missing)

    if inventory.session_breakdown:
        raw_sessions = Table(title="Raw coverage by session")
        raw_sessions.add_column("Session", style="bold")
        raw_sessions.add_column("Modality")
        raw_sessions.add_column("Subjects", justify="right")
        raw_sessions.add_column("Observations", justify="right")
        raw_sessions.add_column("Data types", style="cyan")
        for session, summary in inventory.session_breakdown.items():
            for modality, counts in summary.raw_modalities.items():
                raw_sessions.add_row(
                    session,
                    modality,
                    str(counts.n_subjects),
                    str(counts.n_observations),
                    ", ".join(counts.suffixes),
                )
        if raw_sessions.row_count:
            console.print(raw_sessions)

        derivative_sessions = Table(title="Derivative model coverage by session")
        derivative_sessions.add_column("Session", style="bold")
        derivative_sessions.add_column("Derivative")
        derivative_sessions.add_column("Modality")
        derivative_sessions.add_column("Subjects", justify="right")
        derivative_sessions.add_column("Observations", justify="right")
        derivative_sessions.add_column("Models", style="cyan")
        for session, summary in inventory.session_breakdown.items():
            for derivative, products in summary.derivative_products.items():
                for modality, counts in products.items():
                    derivative_sessions.add_row(
                        session,
                        derivative,
                        modality,
                        str(counts.n_subjects),
                        str(counts.n_observations),
                        ", ".join(counts.models) or "—",
                    )
        if derivative_sessions.row_count:
            console.print(derivative_sessions)

        session_gaps = Table(title="Processing gaps by session")
        session_gaps.add_column("Session", style="bold")
        session_gaps.add_column("Modality")
        session_gaps.add_column("Raw", justify="right")
        session_gaps.add_column("Processed", justify="right")
        session_gaps.add_column("Missing", justify="right", style="yellow")
        session_gaps.add_column("Coverage", justify="right", style="cyan")
        for session, summary in inventory.session_breakdown.items():
            for modality, counts in summary.processing_gaps.items():
                coverage_pct = (
                    100.0 * counts.processed_observations / counts.raw_observations
                    if counts.raw_observations
                    else 0.0
                )
                session_gaps.add_row(
                    session,
                    modality,
                    str(counts.raw_observations),
                    str(counts.processed_observations),
                    str(counts.missing_observations),
                    f"{coverage_pct:.1f}%",
                )
        if session_gaps.row_count:
            console.print(session_gaps)

    for warning in inventory.warnings:
        console.print(f"[yellow]Warning:[/yellow] {warning}")


@app.command("inspect")
def inspect_command(
    bids_dir: Path = typer.Argument(..., help="BIDS dataset directory.", exists=True, file_okay=False),
    rawdata_dir: Optional[Path] = typer.Option(
        None,
        "--rawdata-dir",
        help="Raw BIDS data directory, absolute or relative to BIDS_DIR (for example: rawdata).",
    ),
    derivatives: bool = typer.Option(False, "--derivatives", help="Include datasets beneath derivatives/."),
    processing_gaps: bool = typer.Option(
        False,
        "--processing-gaps",
        help="Compare raw observations with available derivative products.",
    ),
    by_session: bool = typer.Option(
        False,
        "--by-session",
        help="Break raw and derivative coverage counts out by session label.",
    ),
    details: bool = typer.Option(False, "--details", help="Show per-model derivative coverage."),
    participant_label: Optional[List[str]] = typer.Option(None, "--participant-label", "-p", help="Participant label to include; repeat for multiple labels."),
    session_label: Optional[List[str]] = typer.Option(None, "--session-label", "-s", help="Session label to include; repeat for multiple labels."),
    output_format: str = typer.Option("text", "--format", help="Output format: text or json."),
    output: Optional[Path] = typer.Option(None, "--output", "-o", help="Write the report to a file."),
):
    """Inspect raw BIDS contents and available derivative datasets."""
    from qmri_neuropipe.io.bids_inventory import inspect_bids_dataset

    normalized_format = output_format.lower()
    if normalized_format not in {"text", "json"}:
        console.print("[bold red]Error:[/bold red] --format must be either text or json.")
        raise typer.Exit(code=2)
    if output and normalized_format != "json":
        console.print("[bold red]Error:[/bold red] --output currently requires --format json.")
        raise typer.Exit(code=2)

    try:
        inventory = inspect_bids_dataset(
            bids_dir,
            rawdata_dir=rawdata_dir,
            participants=participant_label,
            sessions=session_label,
            include_derivatives=derivatives or details or processing_gaps,
            include_processing_gaps=processing_gaps,
            include_session_breakdown=by_session,
        )
    except Exception as exc:
        console.print(f"[bold red]Inspection failed:[/bold red] {exc}")
        raise typer.Exit(code=1)

    if normalized_format == "json":
        rendered = json.dumps(inventory.to_dict(), indent=2, sort_keys=True)
        if output:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(rendered + "\n", encoding="utf-8")
            console.print(f"[green]Inventory written to:[/green] {output}")
        else:
            # Avoid Rich's terminal-width wrapping, which would corrupt JSON
            # string values when stdout is consumed programmatically.
            typer.echo(rendered)
    else:
        _print_inventory(inventory, details=details)


